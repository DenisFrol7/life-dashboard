[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$testToken = [guid]::NewGuid().ToString('N').Substring(0, 12)
$sourceDatabase = "life_dashboard_restore_test_${testToken}_source"
$targetDatabase = "life_dashboard_restore_test_${testToken}_target"
$containerScript = "/tmp/life-dashboard-restore-test-$testToken.sh"
$containerArchive = "/tmp/life-dashboard-restore-test-$testToken.dump"
$containerCorruptArchive = "/tmp/life-dashboard-restore-test-$testToken-invalid.dump"
$containerId = $null
$createdDatabases = @()

function Invoke-TestSql([string]$Database, [string]$Sql) {
    $output = $Sql | & docker compose exec -T postgres sh -c `
        'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$1" -qAt' sh $Database
    if ($LASTEXITCODE -ne 0) { throw "Test SQL failed in $Database." }
    return ($output -join "`n").Trim()
}

function Invoke-TestRestore([string]$Archive) {
    # Native stderr is expected for the rollback and corrupt-archive scenarios.
    $previousPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $output = & docker compose exec -T -e "POSTGRES_DB=$targetDatabase" postgres `
            sh $containerScript $Archive 2>&1
        $restoreExit = $LASTEXITCODE
    }
    finally { $ErrorActionPreference = $previousPreference }
    return [pscustomobject]@{ ExitCode = $restoreExit; Output = ($output | Out-String) }
}

$fixtureSchema = @'
CREATE TABLE a_restore_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE z_restore_failure (id integer PRIMARY KEY, probe_id bigint REFERENCES a_restore_probe(id), note text);
CREATE VIEW restore_probe_names AS SELECT name FROM a_restore_probe;
'@
$snapshotSql = @'
SELECT jsonb_build_object(
    'rows', (SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM a_restore_probe t),
    'children', (SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM z_restore_failure t),
    'sequence', (SELECT last_value FROM a_restore_probe_id_seq),
    'view', pg_get_viewdef('restore_probe_names'::regclass, true),
    'constraints', (SELECT jsonb_agg(pg_get_constraintdef(oid) ORDER BY conname)
                    FROM pg_constraint WHERE conrelid IN ('a_restore_probe'::regclass, 'z_restore_failure'::regclass))
);
'@
$objectIdsSql = @'
SELECT jsonb_build_object('table', 'a_restore_probe'::regclass::oid,
                         'child', 'z_restore_failure'::regclass::oid,
                         'view', 'restore_probe_names'::regclass::oid,
                         'sequence', 'a_restore_probe_id_seq'::regclass::oid);
'@

Push-Location $repoRoot
try {
    foreach ($database in @($sourceDatabase, $targetDatabase)) {
        if ($database -notmatch '^life_dashboard_restore_test_[a-f0-9]{12}_(source|target)$') {
            throw 'Unexpected test database name.'
        }
    }
    $containerId = (& docker compose ps -q postgres).Trim()
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($containerId)) {
        throw 'PostgreSQL is not running.'
    }
    & docker cp (Join-Path $PSScriptRoot 'postgres\restore.sh') "${containerId}:${containerScript}"
    if ($LASTEXITCODE -ne 0) { throw 'Could not copy the restore script.' }

    foreach ($database in @($sourceDatabase, $targetDatabase)) {
        & docker compose exec -T postgres sh -c 'createdb -U "$POSTGRES_USER" "$1"' sh $database
        if ($LASTEXITCODE -ne 0) { throw "Could not create $database." }
        $createdDatabases += $database
        Invoke-TestSql $database $fixtureSchema | Out-Null
    }
    Invoke-TestSql $sourceDatabase @'
INSERT INTO a_restore_probe(name) VALUES ('Archive first'), ('Archive second');
INSERT INTO z_restore_failure VALUES (1, 2, 'Archived child');
'@ | Out-Null
    Invoke-TestSql $targetDatabase @'
INSERT INTO a_restore_probe(name) VALUES ('Current row');
INSERT INTO z_restore_failure VALUES (1, 1, 'Current child');
'@ | Out-Null

    & docker compose exec -T postgres sh -c `
        'pg_dump -U "$POSTGRES_USER" -d "$1" --format=custom --file="$2"' sh $sourceDatabase $containerArchive
    if ($LASTEXITCODE -ne 0) { throw 'Could not create the fixture archive.' }
    $result = Invoke-TestRestore $containerArchive
    if ($result.ExitCode -ne 0) { throw "Successful restore failed: $($result.Output)" }
    if ((Invoke-TestSql $sourceDatabase $snapshotSql) -cne (Invoke-TestSql $targetDatabase $snapshotSql)) {
        throw 'Successful restore did not reproduce the archived data, sequence and schema.'
    }
    Write-Host 'PASS: successful restore reproduces data, sequence, constraints and view.'

    Invoke-TestSql $targetDatabase @'
UPDATE a_restore_probe SET name = 'Current state before failed restore';
UPDATE z_restore_failure SET note = 'Current child before failed restore';
SELECT setval('a_restore_probe_id_seq', 73);
CREATE FUNCTION reject_restore_test_table() RETURNS event_trigger LANGUAGE plpgsql AS $$
DECLARE command record;
BEGIN
    FOR command IN SELECT * FROM pg_event_trigger_ddl_commands() LOOP
        IF command.object_type = 'table' AND command.object_identity = 'public.z_restore_failure' THEN
            RAISE EXCEPTION 'Intentional restore test failure after replacing the first table';
        END IF;
    END LOOP;
END;
$$;
CREATE EVENT TRIGGER reject_restore_test ON ddl_command_end
    WHEN TAG IN ('CREATE TABLE') EXECUTE FUNCTION reject_restore_test_table();
'@ | Out-Null
    $beforeFailure = Invoke-TestSql $targetDatabase $snapshotSql
    $beforeObjectIds = Invoke-TestSql $targetDatabase $objectIdsSql
    $result = Invoke-TestRestore $containerArchive
    if ($result.ExitCode -eq 0 -or $result.Output -notlike '*Intentional restore test failure*') {
        throw 'The injected SQL failure did not occur.'
    }
    if ((Invoke-TestSql $targetDatabase $snapshotSql) -cne $beforeFailure -or
        (Invoke-TestSql $targetDatabase $objectIdsSql) -cne $beforeObjectIds) {
        throw 'Failed restore changed the pre-existing data or database objects.'
    }
    Write-Host 'PASS: a SQL failure rolls back dropped/recreated objects and preserves existing data.'

    'invalid archive' | & docker compose exec -T postgres tee $containerCorruptArchive | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Could not create the invalid fixture archive.' }
    $result = Invoke-TestRestore $containerCorruptArchive
    if ($result.ExitCode -eq 0 -or $result.Output -notlike '*does not appear to be a valid archive*') {
        throw "Expected invalid archive rejection: $($result.Output)"
    }
    if ((Invoke-TestSql $targetDatabase $snapshotSql) -cne $beforeFailure -or
        (Invoke-TestSql $targetDatabase $objectIdsSql) -cne $beforeObjectIds) {
        throw 'Invalid archive changed the target database.'
    }
    Write-Host 'PASS: invalid archive is rejected without changing the target database.'
}
finally {
    try {
        foreach ($database in $createdDatabases) {
            & docker compose exec -T postgres sh -c 'dropdb -U "$POSTGRES_USER" --if-exists "$1"' sh $database
            if ($LASTEXITCODE -ne 0) { Write-Warning "Could not clean up test database $database." }
        }
        if ($containerId) {
            & docker compose exec -T postgres rm -f -- $containerScript $containerArchive $containerCorruptArchive | Out-Null
        }
    }
    finally { Pop-Location }
}
